-- GoCart base schema for a fresh LOCAL/development database.
-- This is a proposed migration and has not been applied anywhere.
-- products.id is bigint to match the existing Flutter models and RPCs.

begin;

create extension if not exists pgcrypto with schema extensions;

create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  name text not null check (length(btrim(name)) between 1 and 100),
  email text not null,
  role text not null check (role in ('user', 'merchant', 'admin')),
  merchant_status text not null default 'pending'
    check (merchant_status in ('pending', 'approved', 'suspended')),
  created_at timestamptz not null default now()
);

create index profiles_role_status_idx
  on public.profiles (role, merchant_status);

create table public.products (
  id bigint generated by default as identity primary key,
  merchant_id uuid not null references public.profiles (id) on delete restrict,
  name text not null check (length(btrim(name)) between 1 and 150),
  description text not null default '',
  original_price numeric(10, 2) not null check (original_price > 0),
  offer_price numeric(10, 2) not null check (offer_price > 0),
  -- Retained because current clients/migrations still write and read `price`.
  price numeric(10, 2) not null check (price > 0),
  stock integer not null default 0 check (stock >= 0 and stock <= 1000000),
  category text not null check (length(btrim(category)) > 0),
  image_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint products_offer_not_above_original
    check (offer_price <= original_price),
  constraint products_price_matches_offer
    check (price = offer_price),
  constraint products_category_allowed
    check (category in (
      'Electronics',
      'Mobiles & Tablets',
      'Fashion',
      'Beauty & Personal Care',
      'Home & Kitchen',
      'Appliances',
      'Grocery & Food',
      'Sports & Fitness',
      'Toys & Baby',
      'Automotive'
    ))
);

create index products_created_at_idx on public.products (created_at desc);
create index products_category_created_at_idx
  on public.products (category, created_at desc);
create index products_merchant_id_idx on public.products (merchant_id);

create table public.cart_items (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles (id) on delete cascade,
  product_id bigint not null references public.products (id) on delete cascade,
  quantity integer not null check (quantity between 1 and 99),
  created_at timestamptz not null default now(),
  constraint cart_items_user_product_key unique (user_id, product_id)
);

create index cart_items_user_created_at_idx
  on public.cart_items (user_id, created_at desc);

-- New profiles start with no merchant privileges. Signup may create buyer or
-- merchant profiles; only an existing admin function can approve a merchant.
create or replace function public.set_initial_profile_status()
returns trigger
language plpgsql
security definer
set search_path = ''
as $function$
begin
  -- Authenticated clients may insert only their own profile. A trusted local
  -- seed/admin operation has no auth.uid() and may provision the first admin.
  if (select auth.uid()) is not null
     and (select auth.uid()) is distinct from new.id then
    raise exception 'PROFILE_OWNER_MISMATCH';
  end if;
  if new.role = 'admin' and (select auth.uid()) is not null then
    raise exception 'ADMIN_PROFILE_CREATION_NOT_ALLOWED';
  end if;
  select u.email into new.email
  from auth.users u
  where u.id = new.id;
  if new.email is null then raise exception 'AUTH_EMAIL_REQUIRED'; end if;
  if new.role = 'merchant' then
    new.merchant_status := 'pending';
  else
    new.merchant_status := 'approved';
  end if;
  return new;
end;
$function$;

revoke all on function public.set_initial_profile_status()
  from public, anon, authenticated;

create trigger profiles_set_initial_status
before insert on public.profiles
for each row execute function public.set_initial_profile_status();

-- RLS policies cannot query profiles recursively to discover whether the
-- caller is an admin. This narrowly scoped helper runs as its owner and returns
-- only a boolean for the current JWT identity.
create or replace function public.is_current_user_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $function$
  select exists (
    select 1
    from public.profiles p
    where p.id = (select auth.uid())
      and p.role = 'admin'
  );
$function$;

revoke all on function public.is_current_user_admin()
  from public, anon, authenticated;
grant execute on function public.is_current_user_admin() to authenticated;

-- ProductService uploads public images beneath the signed-in merchant's UUID
-- folder, caps images at 5 MiB, and uses JPEG/PNG/WebP. Supabase Storage owns
-- these schemas/tables; this migration configures only this app's bucket.
insert into storage.buckets (
  id, name, public, file_size_limit, allowed_mime_types
)
values (
  'product-images',
  'product-images',
  true,
  5242880,
  array['image/jpeg', 'image/png', 'image/webp']::text[]
)
on conflict (id) do nothing;

do $verify_product_image_bucket$
begin
  if not exists (
    select 1 from storage.buckets b
    where b.id = 'product-images'
      and b.public is true
      and b.file_size_limit = 5242880
      and b.allowed_mime_types = array['image/jpeg', 'image/png', 'image/webp']::text[]
  ) then
    raise exception 'PRODUCT_IMAGE_BUCKET_CONFIG_MISMATCH';
  end if;
end;
$verify_product_image_bucket$;

create policy "Public can read product images"
  on storage.objects for select to anon, authenticated
  using (bucket_id = 'product-images');
create policy "Approved merchants upload own product images"
  on storage.objects for insert to authenticated
  with check (
    bucket_id = 'product-images'
    and (storage.foldername(name))[1] = (select auth.uid())::text
    and exists (
      select 1 from public.profiles p
      where p.id = (select auth.uid())
        and p.role = 'merchant'
        and p.merchant_status = 'approved'
    )
  );
create policy "Owners and admins delete product images"
  on storage.objects for delete to authenticated
  using (
    bucket_id = 'product-images'
    and (
      (storage.foldername(name))[1] = (select auth.uid())::text
      or (select public.is_current_user_admin())
    )
  );

alter table public.profiles enable row level security;
alter table public.products enable row level security;
alter table public.cart_items enable row level security;

create policy "Profiles are readable by signed-in users"
  on public.profiles for select to authenticated
  using (
    id = (select auth.uid())
    or (select public.is_current_user_admin())
  );
create policy "Users create their own non-admin profile"
  on public.profiles for insert to authenticated
  with check (
    id = (select auth.uid())
    and role in ('user', 'merchant')
  );
create policy "Users update their own profile"
  on public.profiles for update to authenticated
  using (id = (select auth.uid()))
  with check (id = (select auth.uid()));

create policy "Catalog is readable"
  on public.products for select to anon, authenticated using (true);
create policy "Merchants manage own products"
  on public.products for all to authenticated
  using (
    merchant_id = (select auth.uid())
    and exists (
      select 1 from public.profiles p
      where p.id = (select auth.uid())
        and p.role = 'merchant'
        and p.merchant_status = 'approved'
    )
  )
  with check (
    merchant_id = (select auth.uid())
    and exists (
      select 1 from public.profiles p
      where p.id = (select auth.uid())
        and p.role = 'merchant'
        and p.merchant_status = 'approved'
    )
  );
create policy "Admins manage products"
  on public.products for all to authenticated
  using (exists (
    select 1 from public.profiles p
    where p.id = (select auth.uid()) and p.role = 'admin'
  ))
  with check (exists (
    select 1 from public.profiles p
    where p.id = (select auth.uid()) and p.role = 'admin'
  ));

create policy "Users can view own cart"
  on public.cart_items for select to authenticated
  using (user_id = (select auth.uid()));
create policy "Users delete own cart rows"
  on public.cart_items for delete to authenticated
  using (user_id = (select auth.uid()));

-- Column grants restrict role/ownership/status and stock writes. Later
-- hardening migrations further revoke direct cart mutations.
revoke all on public.profiles, public.products, public.cart_items
  from public, anon, authenticated;
grant select on public.profiles to authenticated;
grant insert (id, name, email, role) on public.profiles to authenticated;
grant update (name) on public.profiles to authenticated;
grant select on public.products to anon, authenticated;
grant insert (
  merchant_id, name, description, original_price, offer_price, price,
  category, image_url
) on public.products to authenticated;
grant update (
  name, description, original_price, offer_price, price, category,
  image_url, updated_at
) on public.products to authenticated;
grant delete on public.products to authenticated;
grant select, delete on public.cart_items to authenticated;

create or replace function public.add_to_cart(
  p_product_id bigint,
  p_quantity integer default 1
)
returns void
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_user uuid := (select auth.uid());
  v_stock integer;
begin
  if v_user is null then raise exception 'NOT_AUTHENTICATED'; end if;
  if p_quantity is null or p_quantity < 1 or p_quantity > 99 then
    raise exception 'INVALID_QUANTITY';
  end if;

  select p.stock into v_stock
  from public.products p
  where p.id = p_product_id
  for update;
  if not found then raise exception 'PRODUCT_NOT_FOUND'; end if;
  if v_stock < p_quantity then raise exception 'OUT_OF_STOCK'; end if;

  insert into public.cart_items (user_id, product_id, quantity)
  values (v_user, p_product_id, p_quantity)
  on conflict (user_id, product_id) do update
    set quantity = public.cart_items.quantity + excluded.quantity
    where public.cart_items.quantity + excluded.quantity <= v_stock
      and public.cart_items.quantity + excluded.quantity <= 99;
  if not found then raise exception 'OUT_OF_STOCK'; end if;
end;
$function$;

create or replace function public.update_cart_quantity(
  p_cart_item_id bigint,
  p_quantity integer
)
returns void
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_user uuid := (select auth.uid());
  v_product_id bigint;
  v_stock integer;
begin
  if v_user is null then raise exception 'NOT_AUTHENTICATED'; end if;
  if p_quantity is null or p_quantity < 1 or p_quantity > 99 then
    raise exception 'INVALID_QUANTITY';
  end if;

  select ci.product_id into v_product_id
  from public.cart_items ci
  where ci.id = p_cart_item_id and ci.user_id = v_user;
  if not found then raise exception 'CART_ITEM_NOT_FOUND'; end if;

  select p.stock into v_stock from public.products p
  where p.id = v_product_id for update;
  if not found or v_stock < p_quantity then raise exception 'OUT_OF_STOCK'; end if;

  update public.cart_items ci set quantity = p_quantity
  where ci.id = p_cart_item_id and ci.user_id = v_user;
end;
$function$;

-- Compatibility RPC still called by the current signup screen. It deliberately
-- does not self-approve: the screen must be updated to show a pending state and
-- the admin approval path is `admin_set_merchant_status` in the next migration.
create or replace function public.approve_my_merchant_account()
returns boolean
language plpgsql
security definer
set search_path = ''
as $function$
begin
  if (select auth.uid()) is null then raise exception 'NOT_AUTHENTICATED'; end if;
  return false;
end;
$function$;

revoke all on function public.add_to_cart(bigint, integer)
  from public, anon, authenticated;
revoke all on function public.update_cart_quantity(bigint, integer)
  from public, anon, authenticated;
revoke all on function public.approve_my_merchant_account()
  from public, anon, authenticated;
grant execute on function public.add_to_cart(bigint, integer) to authenticated;
grant execute on function public.update_cart_quantity(bigint, integer)
  to authenticated;
grant execute on function public.approve_my_merchant_account() to authenticated;

commit;
