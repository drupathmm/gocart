begin;

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  buyer_id uuid not null references auth.users(id) on delete cascade,
  status text not null default 'placed'
    check (status in ('placed', 'processing', 'shipped', 'delivered', 'cancelled')),
  payment_method text not null default 'demo'
    check (payment_method = 'demo'),
  payment_status text not null default 'demo_paid'
    check (payment_status = 'demo_paid'),
  total numeric(12, 2) not null check (total >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id bigint references public.products(id) on delete set null,
  merchant_id uuid not null,
  product_name text not null,
  unit_price numeric(12, 2) not null check (unit_price >= 0),
  quantity integer not null check (quantity > 0),
  line_total numeric(12, 2) not null check (line_total >= 0),
  created_at timestamptz not null default now()
);

create index if not exists orders_buyer_created_at_idx
  on public.orders (buyer_id, created_at desc);
create index if not exists order_items_order_id_idx
  on public.order_items (order_id);
create index if not exists order_items_merchant_id_idx
  on public.order_items (merchant_id);

alter table public.orders enable row level security;
alter table public.order_items enable row level security;

drop policy if exists "Buyers can view own orders" on public.orders;
create policy "Buyers can view own orders"
  on public.orders for select to authenticated
  using (buyer_id = (select auth.uid()));

drop policy if exists "Buyers and merchants can view order items" on public.order_items;
create policy "Buyers and merchants can view order items"
  on public.order_items for select to authenticated
  using (
    merchant_id = (select auth.uid())
    or exists (
      select 1 from public.orders o
      where o.id = order_id and o.buyer_id = (select auth.uid())
    )
  );

revoke all privileges on table public.orders from anon, authenticated;
revoke all privileges on table public.order_items from anon, authenticated;
grant select on table public.orders, public.order_items to authenticated;

create or replace function public.place_demo_order()
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_buyer_id uuid;
  v_order_id uuid;
  v_cart_ids bigint[];
  v_cart_count integer;
  v_item_count integer := 0;
  v_total numeric(12, 2) := 0;
  v_line record;
begin
  v_buyer_id := (select auth.uid());
  if v_buyer_id is null then
    raise exception 'You must be signed in to place an order.';
  end if;

  -- Snapshot this checkout's cart rows. Newly added rows in another tab stay
  -- in the cart instead of being accidentally removed by this checkout.
  select array_agg(ci.id order by ci.id), count(*)::integer
    into v_cart_ids, v_cart_count
  from public.cart_items ci
  where ci.user_id = v_buyer_id;

  if coalesce(v_cart_count, 0) = 0 then
    raise exception 'Your cart is empty.';
  end if;

  -- Use the same product-before-cart lock order as the cart RPCs. This keeps
  -- stock validation and decrement safe when buyers check out concurrently.
  perform p.id
  from public.products p
  join public.cart_items ci on ci.product_id = p.id
  where ci.id = any(v_cart_ids) and ci.user_id = v_buyer_id
  order by p.id
  for update of p;

  perform ci.id
  from public.cart_items ci
  where ci.id = any(v_cart_ids) and ci.user_id = v_buyer_id
  order by ci.id
  for update of ci;

  for v_line in
    select ci.id, ci.product_id, ci.quantity, p.merchant_id, p.name,
           p.offer_price, p.stock
    from public.cart_items ci
    join public.products p on p.id = ci.product_id
    where ci.id = any(v_cart_ids) and ci.user_id = v_buyer_id
    order by p.id
  loop
    if v_line.quantity <= 0 then
      raise exception 'A cart item has an invalid quantity.';
    end if;
    if v_line.stock < v_line.quantity then
      raise exception 'Not enough stock for "%".', v_line.name;
    end if;

    v_total := v_total + round(v_line.offer_price * v_line.quantity, 2);
    v_item_count := v_item_count + 1;
  end loop;

  if v_item_count <> v_cart_count then
    raise exception 'A product in your cart is no longer available.';
  end if;
  if v_total <= 0 then
    raise exception 'The order total must be greater than zero.';
  end if;

  insert into public.orders (buyer_id, status, payment_method, payment_status, total)
  values (v_buyer_id, 'placed', 'demo', 'demo_paid', v_total)
  returning id into v_order_id;

  insert into public.order_items (
    order_id, product_id, merchant_id, product_name,
    unit_price, quantity, line_total
  )
  select v_order_id, p.id, p.merchant_id, p.name,
         p.offer_price, ci.quantity, round(p.offer_price * ci.quantity, 2)
  from public.cart_items ci
  join public.products p on p.id = ci.product_id
  where ci.id = any(v_cart_ids) and ci.user_id = v_buyer_id;

  update public.products p
  set stock = p.stock - ci.quantity,
      updated_at = now()
  from public.cart_items ci
  where ci.id = any(v_cart_ids)
    and ci.user_id = v_buyer_id
    and ci.product_id = p.id;

  delete from public.cart_items ci
  where ci.id = any(v_cart_ids) and ci.user_id = v_buyer_id;

  return jsonb_build_object(
    'order_id', v_order_id,
    'total', v_total,
    'item_count', v_item_count
  );
end;
$function$;

revoke all on function public.place_demo_order() from public, anon, authenticated;
grant execute on function public.place_demo_order() to authenticated;

commit;
